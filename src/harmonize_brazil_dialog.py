    # ------------------------------------------------------------ catálogo
    def refresh(self):
        """Botão Atualizar: volta os filtros ao estado inicial e recarrega o catálogo."""
        for w in (self.cmbType, self.cmbRegion, self.txtSearch):
            w.blockSignals(True)                 # evita refiltrar a cada mudança
        self.cmbType.setCurrentIndex(0)          # Todos
        self.cmbRegion.setCurrentIndex(0)        # Todas
        self.txtSearch.clear()
        for w in (self.cmbType, self.cmbRegion, self.txtSearch):
            w.blockSignals(False)
        self.load_collections()
        self.lstCollections.scrollToTop()

    def load_collections(self):
        QtWidgets.QApplication.setOverrideCursor(Qt.CursorShape.WaitCursor)
        try:
            hc.load_config()                 # URL do STAC atualizada a partir do GitHub
            self.collections = hc.list_collections()
        except Exception as exc:  # noqa: BLE001
            self.collections = []
            QtWidgets.QMessageBox.critical(
                self, "Harmonize Brazil",
                tr("Could not read the STAC catalog:\n{0}").format(exc))
        finally:
            QtWidgets.QApplication.restoreOverrideCursor()
        self._apply_filter()

    def _apply_filter(self):
        ctype = self.cmbType.currentData()
        region = self.cmbRegion.currentData()
        query = self.txtSearch.text().strip().lower()
        self.lstCollections.clear()
        # títulos repetidos (ex.: mosaico e voos com o mesmo nome) recebem o id ao lado
        titles = [c["title"] for c in self.collections]
        for c in self.collections:
            if ctype and c["type"] != ctype:
                continue
            if region and c["region"] != region:
                continue
            haystack = " ".join([c["id"], c["title"]] + c["keywords"]).lower()
            if query and query not in haystack:
                continue
            text = c["title"]
            if titles.count(c["title"]) > 1 and c["id"] != c["title"]:
                text = "{0}  ({1})".format(c["title"], c["id"])
            item = QtWidgets.QListWidgetItem(text)
            item.setData(ROLE, c)
            item.setToolTip(c["description"])
            self.lstCollections.addItem(item)
        if self.lstCollections.count():
            self.lstCollections.setCurrentRow(0)
        else:
            self.txtInfo.setHtml("<i>{0}</i>".format(tr("No collection matches these filters.")))

    def selected_collection(self):
        item = self.lstCollections.currentItem()
        return item.data(ROLE) if item else None

    def _show_info(self, current, _previous=None):
        c = current.data(ROLE) if current else None
        if not c:
            self.txtInfo.clear()
            return
        temporal = list(c.get("temporal") or []) + [None, None]
        start, end = temporal[0], temporal[1]
        type_label = tr(TYPE_LABELS[c["type"]]) if c["type"] in TYPE_LABELS else c["type"]
        region_label = tr(REGION_LABELS[c["region"]]) if c["region"] in REGION_LABELS else "-"
        self.txtInfo.setHtml(
            "<b>{id}</b><br>{t}: {tv} | {r}: {rv} | {p}: {s} {to} {e}<br><br>{d}"
            "<br><br><b>{sl}:</b> <a href=\"{su}\">{su}</a>".format(
                id=c["id"],
                t=tr("Type"), tv=type_label,
                r=tr("Region"), rv=region_label,
                p=tr("Period"), s=(start or "?")[:10], to=tr("to"), e=(end or "?")[:10],
                d=c["description"],
                sl=tr("STAC collection"),
                su="{0}/collections/{1}".format(hc.STAC_URL, c["id"])))

        self._set_formats(hc.formats_for(c))

        d_start = QDate.fromString((start or "")[:10], "yyyy-MM-dd")
        d_end = QDate.fromString((end or "")[:10], "yyyy-MM-dd")
        self._extent = (d_start, d_end) if d_start.isValid() and d_end.isValid() else None
        if self._extent:
            for w in (self.dtStart, self.dtEnd):
                w.setCalendarRange(d_start, d_end)
            self.dtEnd.setDate(d_end)
            self.dtStart.setDate(max(d_start, d_end.addMonths(-3)))

