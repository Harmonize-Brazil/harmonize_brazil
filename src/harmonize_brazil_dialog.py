    def _set_formats(self, formats):
        """Preenche o combo de formato; mantém a escolha atual se ainda for válida."""
        current = self.cmbFormat.currentData()
        if [self.cmbFormat.itemData(i) for i in range(self.cmbFormat.count())] == formats:
            return
        self.cmbFormat.clear()
        for fmt in formats:
            if fmt.startswith(hc.ASSET_PREFIX):
                label = "GeoTIFF: {0}".format(fmt[len(hc.ASSET_PREFIX):])   # banda do cubo
            else:
                label = tr(FORMAT_LABELS[fmt])
            self.cmbFormat.addItem(label, fmt)
        if current in formats:
            self.cmbFormat.setCurrentIndex(formats.index(current))

    def _browse(self):
        path = QtWidgets.QFileDialog.getExistingDirectory(
            self, tr("Output folder"), self.txtOutDir.text())
        if path:
            self.txtOutDir.setText(path)

    # ------------------------------------------------------------ OK
    def accept(self):
        """Valida antes de fechar; só fecha se tudo estiver correto."""
        def warn(msg):
            QtWidgets.QMessageBox.warning(self, "Harmonize Brazil", msg)

        if not self.selected_collection():
            return warn(tr("Select a collection."))
        for w in (self.dtStart, self.dtEnd):
            if not w.isValid():
                w.edit.setFocus()
                return warn(tr("Invalid date: {0}. Use the format dd/mm/yyyy.").format(w.edit.text()))
        start, end = self.dtStart.date(), self.dtEnd.date()
        if start > end:
            return warn(tr("The start date is after the end date."))
        if self._extent and (end < self._extent[0] or start > self._extent[1]):
            return warn(tr("The selected period is outside the period available for this collection "
                           "({0} to {1}).").format(self._extent[0].toString(DATE_FORMAT),
                                                   self._extent[1].toString(DATE_FORMAT)))
        if not self.txtOutDir.text().strip():
            return warn(tr("Enter the output folder."))
        QgsSettings().setValue(SETTINGS_DIR, self.txtOutDir.text().strip())
        super().accept()

    def params(self):
        return {
            "collection": self.selected_collection(),
            "start": self.dtStart.date().toString("yyyy-MM-dd"),
            "end": self.dtEnd.date().toString("yyyy-MM-dd"),
            "fmt": self.cmbFormat.currentData(),
            "out_dir": self.txtOutDir.text().strip(),
            "load": self.chkLoad.isChecked(),
        }
