import os

from qgis.PyQt import uic
from qgis.PyQt import QtWidgets
from qgis.PyQt.QtCore import QCoreApplication, QDate, Qt, QT_TRANSLATE_NOOP
from qgis.PyQt.QtGui import QIcon
from qgis.core import QgsSettings

from . import harmonize_core as hc

# This loads your .ui file so that PyQt can populate your plugin with the elements from Qt Designer
FORM_CLASS, _ = uic.loadUiType(
    os.path.join(
        os.path.dirname(__file__),
        'harmonize_brazil_dialog_base.ui'),
    from_imports=True,
    import_from='harmonize_brazil')

# Contexto "@default": é o que o pylupdate5 atribui às chamadas tr("...")
# fora de classes Qt, então extração (.ts) e execução usam o mesmo contexto.
CTX = "@default"


def tr(message):
    return QCoreApplication.translate(CTX, message)


# Rótulos marcados com QT_TRANSLATE_NOOP: o pylupdate5 os encontra, mas a
# tradução só acontece em tempo de execução (depois que o tradutor foi instalado).
TYPE_OPTIONS = [(QT_TRANSLATE_NOOP("@default", "All types"), ""),
                (QT_TRANSLATE_NOOP("@default", "Drone"), "drone"),
                (QT_TRANSLATE_NOOP("@default", "Health"), "health"),
                (QT_TRANSLATE_NOOP("@default", "Climate"), "climate"),
                (QT_TRANSLATE_NOOP("@default", "Data cube"), "datacube")]
REGION_OPTIONS = [(QT_TRANSLATE_NOOP("@default", "All regions"), ""),
                  (QT_TRANSLATE_NOOP("@default", "Northeast"), "NE"),
                  (QT_TRANSLATE_NOOP("@default", "North"), "NO")]
FORMAT_LABELS = {"geojson": "GeoJSON",
                 "shapefile": QT_TRANSLATE_NOOP("@default", "Shapefile (zip)"),
                 "geotiff": "GeoTIFF (.tif)"}
TYPE_LABELS = {v: k for k, v in TYPE_OPTIONS if v}
REGION_LABELS = {v: k for k, v in REGION_OPTIONS if v}
SETTINGS_DIR = "harmonize_brazil/out_dir"
ROLE = Qt.ItemDataRole.UserRole


class HarmonizeBrazilDialog(QtWidgets.QDialog, FORM_CLASS):
    def __init__(self, parent=None):
        """Constructor."""
        super(HarmonizeBrazilDialog, self).__init__(parent)
        self.setupUi(self)
        self.setWindowIcon(QIcon(os.path.join(os.path.dirname(__file__), 'icon.png')))
        self.collections = []

        for label, value in TYPE_OPTIONS:
            self.cmbType.addItem(tr(label), value)
        for label, value in REGION_OPTIONS:
            self.cmbRegion.addItem(tr(label), value)
        self._set_formats(hc.VECTOR_FORMATS)

        self.txtSearch.setMinimumWidth(160)   # evita que os combos espremam a busca

        default_dir = os.path.join(os.path.expanduser("~"), "harmonize_brazil")
        self.txtOutDir.setText(QgsSettings().value(SETTINGS_DIR, default_dir))

        self.cmbType.currentIndexChanged.connect(self._apply_filter)
        self.cmbRegion.currentIndexChanged.connect(self._apply_filter)
        self.txtSearch.textChanged.connect(self._apply_filter)
        self.lstCollections.currentItemChanged.connect(self._show_info)
        self.btnRefresh.clicked.connect(self.load_collections)
        self.btnOutDir.clicked.connect(self._browse)

        # Botão "About us" à esquerda do OK/Cancelar; não fecha o diálogo
        self.btnAbout = self.button_box.addButton(
            tr("About us"), QtWidgets.QDialogButtonBox.ButtonRole.HelpRole)
        self.btnAbout.clicked.connect(self._show_about)

    # ------------------------------------------------------------ catálogo
    def load_collections(self):
        QtWidgets.QApplication.setOverrideCursor(Qt.CursorShape.WaitCursor)
        try:
            hc.load_config()                 # URL do STAC atualizada a partir do GitHub
            self.collections = hc.list_collections()
        except Exception as exc:  # noqa: BLE001
            self.collections = []
            QtWidgets.QMessageBox.critical(
                self, "Harmonize Brazil",
                tr("Could not read the STAC catalog:\n{0}").format(exc))
        finally:
            QtWidgets.QApplication.restoreOverrideCursor()
        self._apply_filter()

    def _apply_filter(self):
        ctype = self.cmbType.currentData()
        region = self.cmbRegion.currentData()
        query = self.txtSearch.text().strip().lower()
        self.lstCollections.clear()
        for c in self.collections:
            if ctype and c["type"] != ctype:
                continue
            if region and c["region"] != region:
                continue
            haystack = " ".join([c["id"], c["title"]] + c["keywords"]).lower()
            if query and query not in haystack:
                continue
            item = QtWidgets.QListWidgetItem(c["title"])
            item.setData(ROLE, c)
            item.setToolTip(c["description"])
            self.lstCollections.addItem(item)
        if self.lstCollections.count():
            self.lstCollections.setCurrentRow(0)
        else:
            self.txtInfo.setHtml("<i>{0}</i>".format(tr("No collection matches these filters.")))

    def selected_collection(self):
        item = self.lstCollections.currentItem()
        return item.data(ROLE) if item else None

    def _show_info(self, current, _previous=None):
        c = current.data(ROLE) if current else None
        if not c:
            self.txtInfo.clear()
            return
        temporal = list(c.get("temporal") or []) + [None, None]
        start, end = temporal[0], temporal[1]
        type_label = tr(TYPE_LABELS[c["type"]]) if c["type"] in TYPE_LABELS else c["type"]
        region_label = tr(REGION_LABELS[c["region"]]) if c["region"] in REGION_LABELS else "-"
        self.txtInfo.setHtml(
            "<b>{id}</b><br>{t}: {tv} | {r}: {rv} | {p}: {s} {to} {e}<br><br>{d}"
            "<br><br><b>{sl}:</b> <a href=\"{su}\">{su}</a>".format(
                id=c["id"],
                t=tr("Type"), tv=type_label,
                r=tr("Region"), rv=region_label,
                p=tr("Period"), s=(start or "?")[:10], to=tr("to"), e=(end or "?")[:10],
                d=c["description"],
                sl=tr("STAC collection"),
                su="{0}/collections/{1}".format(hc.STAC_URL, c["id"])))

        self._set_formats(hc.formats_for(c))

        d_start = QDate.fromString((start or "")[:10], "yyyy-MM-dd")
        d_end = QDate.fromString((end or "")[:10], "yyyy-MM-dd")
        if d_start.isValid() and d_end.isValid():
            for w in (self.dtStart, self.dtEnd):
                w.setDateRange(d_start, d_end)
            self.dtEnd.setDate(d_end)
            self.dtStart.setDate(max(d_start, d_end.addMonths(-3)))

    def _show_about(self):
        paragraphs = [
            tr('This work is part of the <a href="https://www.harmonize-tools.org/">Harmonize Project</a>. '
               'Harmonizing multi-scale spatiotemporal data for health in climate change hotspots. '
               'Harmonize is a project in partnership with the Health and Climate Observatory and several '
               'international partners, including the Barcelona Supercomputing Center (BSC). '
               'The project’s objective is to collect, organize and analyze multi-scale spatiotemporal '
               'data for health in climate hotspots.'),
            tr('The <a href="https://harmonize-brazil.github.io/">Earth Observation Data Cube tuned for '
               'Health Response Systems (EODCtHRS)</a> component is based on the integration and '
               'interoperability between specific sets of attention data (climate reanalysis, forecast, '
               'socioeconomic, demographic, health, disease surveillance data and drone images) and '
               'digital infrastructure of the Brazil Data Cube (BDC) Project of the National Institute '
               'for Space Research (INPE), in particular with the Earth Observation datasets of Brazil.'),
            tr('This work is supported by the Wellcome Trust grant number 224694/Z/21/Z.'),
            tr('Explore the data online in the '
               '<a href="https://geolab.inpe.br/bdc/harmonize/explorer/explore">Harmonize Explorer</a>.'),
        ]
        html = "<h3>Harmonize Brazil Catalog</h3>" + "".join(f"<p>{t}</p>" for t in paragraphs)

        box = QtWidgets.QMessageBox(self)
        box.setWindowTitle(tr("About us"))
        box.setTextFormat(Qt.TextFormat.RichText)
        box.setText(html)
        box.setIconPixmap(self.windowIcon().pixmap(64, 64))
        for label in box.findChildren(QtWidgets.QLabel):
            label.setOpenExternalLinks(True)   # links abrem no navegador
        # largura mínima: o QMessageBox padrão fica estreito demais para o texto
        layout = box.layout()
        layout.addItem(QtWidgets.QSpacerItem(520, 0, QtWidgets.QSizePolicy.Policy.Minimum,
                                             QtWidgets.QSizePolicy.Policy.Expanding),
                       layout.rowCount(), 0, 1, layout.columnCount())
        box.exec()

    def _set_formats(self, formats):
        """Preenche o combo de formato; mantém a escolha atual se ainda for válida."""
        current = self.cmbFormat.currentData()
        if [self.cmbFormat.itemData(i) for i in range(self.cmbFormat.count())] == formats:
            return
        self.cmbFormat.clear()
        for fmt in formats:
            if fmt.startswith(hc.ASSET_PREFIX):
                label = "GeoTIFF: {0}".format(fmt[len(hc.ASSET_PREFIX):])   # banda do cubo
            else:
                label = tr(FORMAT_LABELS[fmt])
            self.cmbFormat.addItem(label, fmt)
        if current in formats:
            self.cmbFormat.setCurrentIndex(formats.index(current))

    def _browse(self):
        path = QtWidgets.QFileDialog.getExistingDirectory(
            self, tr("Output folder"), self.txtOutDir.text())
        if path:
            self.txtOutDir.setText(path)

    # ------------------------------------------------------------ OK
    def accept(self):
        """Valida antes de fechar; só fecha se tudo estiver correto."""
        def warn(msg):
            QtWidgets.QMessageBox.warning(self, "Harmonize Brazil", msg)

        if not self.selected_collection():
            return warn(tr("Select a collection."))
        if self.dtStart.date() > self.dtEnd.date():
            return warn(tr("The start date is after the end date."))
        if not self.txtOutDir.text().strip():
            return warn(tr("Enter the output folder."))
        QgsSettings().setValue(SETTINGS_DIR, self.txtOutDir.text().strip())
        super().accept()

    def params(self):
        return {
            "collection": self.selected_collection(),
            "start": self.dtStart.date().toString("yyyy-MM-dd"),
            "end": self.dtEnd.date().toString("yyyy-MM-dd"),
            "fmt": self.cmbFormat.currentData(),
            "out_dir": self.txtOutDir.text().strip(),
            "load": self.chkLoad.isChecked(),
        }
