    # ---------------------------------------------------------------- lista
    def _fill(self, items, selected_ids):
        icon = QgsApplication.getThemeIcon("/mIconSuccess.svg")
        self.tree.blockSignals(True)
        for it in items:
            p_start, p_end = hc.item_period(it)
            period = p_start if p_start == p_end else "{0} {1} {2}".format(p_start, tr("to"), p_end)
            row = QtWidgets.QTreeWidgetItem(["", period, it.get("id", ""), "", ""])
            row.setData(COL_CHECK, ROLE, it)
            row.setFlags(row.flags() | Qt.ItemFlag.ItemIsUserCheckable)
            _key, asset = hc.find_asset(it, self.fmt)
            size = (asset or {}).get("file:size")
            if isinstance(size, (int, float)) and size > 0:
                row.setText(COL_SIZE, hc.format_size(size))
            if not asset:
                row.setText(COL_LOCAL, tr("format not available"))
                row.setCheckState(COL_CHECK, Qt.CheckState.Unchecked)
                row.setDisabled(True)
            else:
                local = hc.is_local(it, self.fmt, self.folder)
                row.setData(COL_LOCAL, ROLE, local)
                if local:
                    row.setText(COL_LOCAL, tr("Yes"))
                    row.setIcon(COL_LOCAL, icon)
                    row.setToolTip(COL_LOCAL, tr("Already downloaded: it will be loaded from the output folder"))
                checked = selected_ids is None or it.get("id") in selected_ids
                row.setCheckState(COL_CHECK, Qt.CheckState.Checked if checked else Qt.CheckState.Unchecked)
            self.tree.addTopLevelItem(row)
        self.tree.blockSignals(False)
        self._update_label()

    def _rows(self):
        return [self.tree.topLevelItem(i) for i in range(self.tree.topLevelItemCount())]

    def _check(self, rule):
        self.tree.blockSignals(True)
        for row in self._rows():
            if not row.isDisabled():
                row.setCheckState(COL_CHECK, Qt.CheckState.Checked if rule(row) else Qt.CheckState.Unchecked)
        self.tree.blockSignals(False)
        self._update_label()

    def selected_ids(self):
        return {row.data(COL_CHECK, ROLE).get("id") for row in self._rows()
                if not row.isDisabled() and row.checkState(COL_CHECK) == Qt.CheckState.Checked}

    def local_count(self):
        return sum(1 for row in self._rows() if row.data(COL_LOCAL, ROLE))

    def _update_label(self):
        rows = self._rows()
        if not rows:
            self.label.setText(tr("No items in the selected period."))
        else:
            self.label.setText(tr("{0} item(s), {1} available locally, {2} selected").format(
                len(rows), self.local_count(), len(self.selected_ids())))

    def accept(self):
        if not self.selected_ids():
            QtWidgets.QMessageBox.warning(self, "Harmonize Brazil",
                                          tr("Select at least one item, or cancel to download the whole period."))
            return
        super().accept()

    # ---------------------------------------------------------------- miniatura
    def _on_current(self, current, _previous=None):
        it = current.data(COL_CHECK, ROLE) if current else None
        self._show_thumbnail((hc.thumbnail_url(it) if it else None) or self.collection.get("thumbnail"))

    def _show_thumbnail(self, url):
        """Mostra a miniatura; o download é assíncrono e não trava a janela."""
        self._url = url
        if self._reply is not None:
            self._reply.abort()
            self._reply = None
        self.thumb.setPixmap(QPixmap())
        if not url:
            self.thumb.setText(tr("No thumbnail"))
            return
        if url in self._cache:
            self._set_thumb(self._cache[url])
            return
        try:
            hc._check_url(url)
        except ValueError:
            self.thumb.setText(tr("No thumbnail"))
            return
        self.thumb.setText(tr("Loading thumbnail..."))
        req = QNetworkRequest(QUrl(url))
        req.setRawHeader(b"User-Agent", hc.USER_AGENT.encode("utf-8"))
        reply = QgsNetworkAccessManager.instance().get(req)
        self._reply = reply
        reply.finished.connect(lambda r=reply, u=url: self._on_thumb_finished(r, u))

    def _on_thumb_finished(self, reply, url):
        if reply is self._reply:
            self._reply = None
        pix = QPixmap()
        if reply.error() == QNetworkReply.NetworkError.NoError:
            pix.loadFromData(bytes(reply.readAll()))
        reply.deleteLater()
        if pix.isNull():
            if url == self._url:
                self.thumb.setText(tr("No thumbnail"))
            return
        self._cache[url] = pix
        if url == self._url:
            self._set_thumb(pix)

    def _set_thumb(self, pix):
        self.thumb.setText("")
        self.thumb.setPixmap(pix.scaled(THUMB_SIZE - 4, THUMB_SIZE - 4, Qt.AspectRatioMode.KeepAspectRatio,
                                        Qt.TransformationMode.SmoothTransformation))

    def reject(self):
        if self._reply is not None:
            self._reply.abort()
        super().reject()

    def done(self, result):
        if self._reply is not None:
            self._reply.abort()
            self._reply = None
        super().done(result)


