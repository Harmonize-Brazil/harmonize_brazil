from qgis.PyQt.QtCore import QLocale, QTranslator, QCoreApplication
from qgis.core import Qgis, QgsApplication, QgsProject, QgsSettings
from qgis.PyQt.QtGui import QIcon
from qgis.PyQt.QtWidgets import QAction, QMessageBox

# Import the code for the dialog
from .harmonize_brazil_dialog import HarmonizeBrazilDialog
from . import harmonize_core as hc
from .harmonize_tasks import HarmonizeDownloadTask, HarmonizePrepareTask
import os.path

MSG_TITLE = "Harmonize Brazil"


class HarmonizeBrazil:
    """QGIS Plugin Implementation."""

    def __init__(self, iface):
        """Constructor.

        :param iface: An interface instance that will be passed to this class
            which provides the hook by which you can manipulate the QGIS
            application at run time.
        :type iface: QgsInterface
        """
        # Save reference to the QGIS interface
        self.iface = iface
        # initialize plugin directory
        self.plugin_dir = os.path.dirname(__file__)
        # initialize locale: segue o idioma do QGIS.
        # pt_BR (ou qualquer pt*) -> i18n/HarmonizeBrazil_pt_BR.qm ; demais -> inglês (idioma-fonte)
        self.translator = None
        locale = QgsSettings().value('locale/userLocale', '') or QLocale().name()
        candidates = [locale[0:5], locale[0:2]] + (['pt_BR'] if locale.startswith('pt') else [])
        for code in candidates:
            locale_path = os.path.join(self.plugin_dir, 'i18n', 'HarmonizeBrazil_{}.qm'.format(code))
            if os.path.exists(locale_path):
                self.translator = QTranslator()
                if self.translator.load(locale_path):
                    QCoreApplication.installTranslator(self.translator)
                break

        # Declare instance attributes
        self.actions = []
        self.menu = self.tr(u'&Harmonize Brazil Catalog')

        # Check if plugin was started the first time in current QGIS session
        # Must be set in initGui() to survive plugin reloads
        self.first_start = None
        self.dlg = None
        self.tasks = []  # mantém referência às tarefas em execução

    # noinspection PyMethodMayBeStatic
    def tr(self, message):
        """Get the translation for a string using Qt translation API.

        We implement this ourselves since we do not inherit QObject.

        :param message: String for translation.
        :type message: str, QString

        :returns: Translated version of message.
        :rtype: QString
        """
        # noinspection PyTypeChecker,PyArgumentList,PyCallByClass
        return QCoreApplication.translate('HarmonizeBrazil', message)


    def add_action(
        self,
        icon_path,
        text,
        callback,
        enabled_flag=True,
        add_to_menu=True,
        add_to_toolbar=True,
        status_tip=None,
        whats_this=None,
        parent=None):
        """Add a toolbar icon to the toolbar.

        :param icon_path: Path to the icon for this action. Can be a resource
            path (e.g. ':/plugins/foo/bar.png') or a normal file system path.
        :type icon_path: str

        :param text: Text that should be shown in menu items for this action.
        :type text: str

        :param callback: Function to be called when the action is triggered.
        :type callback: function

        :param enabled_flag: A flag indicating if the action should be enabled
            by default. Defaults to True.
        :type enabled_flag: bool

        :param add_to_menu: Flag indicating whether the action should also
            be added to the menu. Defaults to True.
        :type add_to_menu: bool

        :param add_to_toolbar: Flag indicating whether the action should also
            be added to the toolbar. Defaults to True.
        :type add_to_toolbar: bool

        :param status_tip: Optional text to show in a popup when mouse pointer
            hovers over the action.
        :type status_tip: str

        :param parent: Parent widget for the new action. Defaults None.
        :type parent: QWidget

        :param whats_this: Optional text to show in the status bar when the
            mouse pointer hovers over the action.

        :returns: The action that was created. Note that the action is also
            added to self.actions list.
        :rtype: QAction
        """

        icon = QIcon(icon_path)
        action = QAction(icon, text, parent)
        action.triggered.connect(callback)
        action.setEnabled(enabled_flag)

        if status_tip is not None:
            action.setStatusTip(status_tip)

        if whats_this is not None:
            action.setWhatsThis(whats_this)

        if add_to_toolbar:
            # Adds plugin icon to Plugins toolbar
            self.iface.addToolBarIcon(action)

        if add_to_menu:
            self.iface.addPluginToWebMenu(
                self.menu,
                action)

        self.actions.append(action)

        return action

    def initGui(self):
        """Create the menu entries and toolbar icons inside the QGIS GUI."""

        icon_path = os.path.join(os.path.dirname(__file__), 'icon.png')
        self.add_action(
            icon_path,
            text=self.tr(u'Harmonize Brazil Catalog'),
            callback=self.run,
            parent=self.iface.mainWindow())

        # will be set False in run()
        self.first_start = True


    def unload(self):
        """Removes the plugin menu item and icon from QGIS GUI."""
        for action in self.actions:
            self.iface.removePluginWebMenu(
                self.tr(u'&Harmonize Brazil Catalog'),
                action)
            self.iface.removeToolBarIcon(action)
        if self.translator:
            QCoreApplication.removeTranslator(self.translator)
            self.translator = None


    def run(self):
        """Abre o diálogo e, após o OK, baixa os dados do STAC."""
        if self.first_start == True:
            self.first_start = False
            self.dlg = HarmonizeBrazilDialog(self.iface.mainWindow())
            self.dlg.load_collections()

        if not self.dlg.exec():
            return  # Cancelar

        p = self.dlg.params()
        bar = self.iface.messageBar()

        # 1) verifica itens e tamanho; 2) confirma se for grande; 3) baixa
        task = HarmonizePrepareTask(p, self._on_prepare_done)
        self.tasks.append(task)
        QgsApplication.taskManager().addTask(task)
        bar.pushMessage(MSG_TITLE, self.tr("Checking files (see the task bar)."), Qgis.Info, 5)

    def _on_prepare_done(self, task, ok):
        if task in self.tasks:
            self.tasks.remove(task)
        bar = self.iface.messageBar()
        if not ok:
            bar.pushMessage(MSG_TITLE, task.error or self.tr("Download canceled."), Qgis.Warning, 10)
            return

        if task.total_bytes > hc.SIZE_WARNING_MB * 1024 ** 2:
            msg = self.tr("The selected period has {0} file(s) to download, totaling {1}.").format(
                task.to_download, hc.format_size(task.total_bytes))
            if task.unknown:
                msg += "\n" + self.tr("{0} file(s) of unknown size are not included in this total.").format(
                    task.unknown)
            msg += "\n\n" + self.tr("Do you want to continue?")
            answer = QMessageBox.question(
                self.iface.mainWindow(), self.tr("Large download"), msg,
                QMessageBox.StandardButton.Yes | QMessageBox.StandardButton.No,
                QMessageBox.StandardButton.No)
            if answer != QMessageBox.StandardButton.Yes:
                bar.pushMessage(MSG_TITLE, self.tr("Download canceled by the user."), Qgis.Info, 5)
                return

        download = HarmonizeDownloadTask(task.params, task.items, self._on_download_done)
        self.tasks.append(download)
        QgsApplication.taskManager().addTask(download)
        bar.pushMessage(MSG_TITLE, self.tr("Download started (see the task bar)."), Qgis.Info, 5)

    def _group(self, col):
        """Grupo da coleção no painel de camadas (cria se não existir)."""
        root = QgsProject.instance().layerTreeRoot()
        name = col["title"]
        return root.findGroup(name) or root.insertGroup(0, name)

    def _on_download_done(self, task, ok):
        if task in self.tasks:
            self.tasks.remove(task)
        bar = self.iface.messageBar()
        if not ok:
            bar.pushMessage(MSG_TITLE, task.error or self.tr("Download canceled."), Qgis.Warning, 10)
            return

        p = task.params
        n_files = len(task.files)
        if not p["load"]:
            bar.pushMessage(MSG_TITLE, self.tr("{0} file(s) saved in {1}").format(n_files, task.out_dir), Qgis.Success, 8)
            return

        group = self._group(p["collection"])
        layers = []
        for path, item in task.files:
            try:
                if p["fmt"] in hc.RASTER_FORMATS:
                    layer = hc.load_raster(path, item["id"], group=group)
                else:
                    layer = hc.load_vector(path, item["id"], group=group)
                props = item.get("properties", {})
                hc.set_temporal(layer, props.get("start_datetime") or props.get("datetime"),
                                props.get("end_datetime") or props.get("datetime"))
                layers.append(layer)
            except Exception as exc:  # noqa: BLE001
                hc.log(self.tr("Failed to load {0}: {1}").format(path, exc), Qgis.Warning)

        # Deixa visível só o período mais recente; os demais via Controlador Temporal
        for layer in layers[:-1]:
            node = group.findLayer(layer.id())
            if node:
                node.setItemVisibilityChecked(False)

        bar.pushMessage(MSG_TITLE, self.tr("{0} layer(s) loaded from {1}").format(len(layers), task.out_dir), Qgis.Success, 8)
